#!/usr/bin/env node
/**
 * Static migration inventory + manifest generation for Identity / Authorization / Activity.
 * Run: node tools/scripts/migration-inventory.mjs [--write]
 */
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const writeManifests = process.argv.includes('--write');

const SERVICES = [
  {
    key: 'identity',
    dir: path.join(repoRoot, 'services/identity-service/migrations'),
    trackingTable: 'identity_schema_migrations',
    foundationId: '001_better_auth.sql',
  },
  {
    key: 'authorization',
    dir: path.join(repoRoot, 'services/authorization-service/migrations'),
    trackingTable: 'authorization_schema_migrations',
    foundationId: '001_authorization_foundation.sql',
  },
  {
    key: 'activity',
    dir: path.join(repoRoot, 'services/activity-service/migrations'),
    trackingTable: 'activity_schema_migrations',
    foundationId: '001_activity_foundation.sql',
  },
];

const DANGEROUS_PATTERNS = [
  { pattern: /\bTRUNCATE\b/i, label: 'TRUNCATE' },
  { pattern: /\bDROP TABLE\b/i, label: 'DROP TABLE' },
  { pattern: /\bDROP COLUMN\b/i, label: 'DROP COLUMN' },
  { pattern: /\bDELETE FROM\b/i, label: 'DELETE FROM' },
  { pattern: /\bCREATE INDEX CONCURRENTLY\b/i, label: 'CREATE INDEX CONCURRENTLY' },
];

function sha256(contents) {
  return createHash('sha256').update(contents.replace(/\r\n/g, '\n'), 'utf8').digest('hex');
}

function listSqlFiles(dir) {
  return readdirSync(dir)
    .filter((file) => file.endsWith('.sql'))
    .sort((left, right) => left.localeCompare(right));
}

function analyzeFile(filePath, fileName) {
  const contents = readFileSync(filePath, 'utf8');
  const flags = [];
  for (const { pattern, label } of DANGEROUS_PATTERNS) {
    if (pattern.test(contents)) {
      flags.push(label);
    }
  }
  if (/\bCREATE EXTENSION\b/i.test(contents)) {
    flags.push('CREATE EXTENSION');
  }
  if (/\bALTER COLUMN\b[^;]*SET NOT NULL/i.test(contents)) {
    flags.push('SET NOT NULL');
  }
  if (/\bDROP CONSTRAINT\b/i.test(contents)) {
    flags.push('DROP CONSTRAINT');
  }
  if (/\bDROP INDEX\b/i.test(contents)) {
    flags.push('DROP INDEX');
  }
  if (/\bEXCLUDE\b/i.test(contents)) {
    flags.push('EXCLUDE CONSTRAINT');
  }
  return {
    id: fileName,
    checksum: sha256(contents),
    flags,
  };
}

function validateNumbering(files) {
  const numbers = files.map((file) => {
    const match = /^(\d+)_/.exec(file);
    return match === null ? null : Number(match[1]);
  });
  const seen = new Set();
  for (const number of numbers) {
    if (number === null) {
      throw new Error(`Migration file missing numeric prefix: ${files.join(', ')}`);
    }
    if (seen.has(number)) {
      throw new Error(`Duplicate migration number ${number} in ${files.join(', ')}`);
    }
    seen.add(number);
  }
}

const matrix = {};

for (const service of SERVICES) {
  const files = listSqlFiles(service.dir);
  validateNumbering(files);
  const migrations = files.map((file) => analyzeFile(path.join(service.dir, file), file));
  const manifest = {
    service: service.key,
    trackingTable: service.trackingTable,
    count: migrations.length,
    foundationId: service.foundationId,
    latestId: migrations[migrations.length - 1]?.id ?? service.foundationId,
    migrations: migrations.map(({ id, checksum, flags }) => ({ id, checksum, flags })),
  };
  matrix[service.key] = manifest;

  if (writeManifests) {
    const manifestPath = path.join(service.dir, 'manifest.json');
    writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');
    console.log(`Wrote ${manifestPath}`);
  }
}

let exitCode = 0;
for (const service of Object.values(matrix)) {
  console.log(
    `\n${service.service}: ${service.count} migrations (${service.foundationId} → ${service.latestId})`,
  );
  for (const migration of service.migrations) {
    const flagText = migration.flags.length > 0 ? ` [${migration.flags.join(', ')}]` : '';
    console.log(`  ${migration.id}${flagText}`);
  }
}

if (writeManifests) {
  for (const service of SERVICES) {
    const entry = matrix[service.key];
    const generatedPath = path.join(
      repoRoot,
      `services/${service.key}-service/src/infrastructure/db/migration-manifest.generated.ts`,
    );
    const contents = `// AUTO-GENERATED by tools/scripts/migration-inventory.mjs — do not edit manually.
export const schemaMigrationManifest = ${JSON.stringify(
      {
        service: entry.service,
        trackingTable: entry.trackingTable,
        count: entry.count,
        foundationId: entry.foundationId,
        latestId: entry.latestId,
      },
      null,
      2,
    )} as const;
`;
    writeFileSync(generatedPath, contents, 'utf8');
    console.log(`Wrote ${generatedPath}`);
  }
}

console.log('\nInventory OK — no duplicate numbering within each service.');
process.exit(exitCode);
